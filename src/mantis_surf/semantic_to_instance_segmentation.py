"""Convert nnUnet semantic segmentation to instance segmentation."""

import logging
import os
from typing import Optional

import anndata as ad
import dask.array as da
import fractal_tasks_core
import numpy as np
import zarr
from fractal_tasks_core.labels import prepare_label_group
from fractal_tasks_core.ngff import load_NgffImageMeta
from fractal_tasks_core.pyramids import build_pyramid
from fractal_tasks_core.roi import (
    array_to_bounding_box_table,
    check_valid_ROI_indices,
    convert_ROI_table_to_indices,
    create_roi_table_from_df_list,
    find_overlaps_in_ROI_indices,
    is_ROI_table_valid,
    load_region,
)
from fractal_tasks_core.tables import write_table
from fractal_tasks_core.utils import rescale_datasets
from pydantic import validate_call

from mantis_surf.utils.instance_utils import run_semantic_to_instance_segmentation
from mantis_surf.utils.masked_loading import _preprocess_input, masked_loading_wrapper

logger = logging.getLogger(__name__)

__OME_NGFF_VERSION__ = fractal_tasks_core.__OME_NGFF_VERSION__


@validate_call
def semantic_to_instance_segmentation(
    *,
    # Fractal parameters
    zarr_url: str,
    # Core parameters
    level: int,
    boundary_label_name: str = "nnunet_boundary",
    semantic_label_name: str = "nnunet_semantic",
    masking_ROI_table: str = "org_ROI_table",
    output_ROI_table: Optional[str] = None,
    output_label_name: Optional[str] = None,
    # nnUnet-related arguments
    select_semantic_class: int = 1,
    gaussian_sigma: float = 2.0,
    watershed_threshold: float = 0.05,
    watershed_sigma_seeds: float = 1.0,
    watershed_sigma_weights: float = 2.0,
    watershed_alpha: float = 1.0,
    watershed_min_size: int = 100,
    gasp_beta: float = 0.5,
    combine_boundary_and_semantic_edges: bool = True,
    overwrite: bool = True,
) -> None:
    """Convert nnUnet semantic segmentation into instance segmentation in numerically increasing order. Uses
    distance watershed and GASP algorithm approach similar to PlantSeg.

    Args:
        zarr_url: Path or url to the individual OME-Zarr image to be processed.
            (standard argument for Fractal tasks, managed by Fractal server).
        level: Pyramid level of the image to be segmented. Choose `0` to
            process at full resolution.
        boundary_label_name: Name of label for boundary segmentation (nnUnet output).
        semantic_label_name: Name of label for semantic class segmentation (nnUnet output),
            e.g. foreground/background or more.
        masking_ROI_table: Name of the ROI table over which the task loops to
            apply nnUnet segmentation. E.g. `organoid_ROI_table` => loop over the organoid
            ROI table (generated by another task)
        output_ROI_table: If provided, a ROI table with that name is created,
            which will contain the bounding boxes of the newly segmented
            labels. ROI tables should have `ROI` in their name.
        output_label_name: Name of the output label image (e.g. `"organoids"`).
        select_semantic_class: Integer label ID for class to select from semantic_label_name.
            Task will return instances of this class. For example, if semantic segmentation has
            3 classes: background, lumen, epithelium - select which one should be instanced.
        gaussian_sigma: Standard deviation value for 3D Gaussian smoothing applied to object
            boundaries to generate probability map-like image. Sigma specified blur in X,Y ;
            Z dimension is scaled accordingly based on pixel spacing and accounts for
            voxel anisotropy.
        watershed_threshold: Threshold value (0 to 1) applied to the boundary probability map
            before computing the distance transform. Values below this threshold are considered
            background. Defaults to 0.05. From PlantSeg dt_watershed function. Higher values make
            probability map edges narrower.
        watershed_sigma_seeds: Standard deviation for Gaussian smoothing applied to
            the seed map (used for initializing the watershed regions). Higher values result
            in more smoothed seeds. Defaults to 1.0. From PlantSeg dt_watershed function. Higher
            values result in fewer seeds.
        watershed_sigma_weights: Standard deviation for Gaussian smoothing applied
            to the weight map. The weight map combines the distance transform and input map
            to guide the watershed. Larger values result in smoother weight maps. Defaults to 2.0.
            From PlantSeg dt_watershed function.
        watershed_alpha: Blending factor to combine the input boundary probability maps
            and the distance transform when constructing the weight map. A higher alpha
            prioritizes the input maps and reduces the contribution from the distance transform.
            Defaults to 1.0. From PlantSeg dt_watershed function.
        watershed_min_size: Minimum size of the segmented regions to retain. Regions
            smaller than this size are removed. Defaults to 100. From PlantSeg dt_watershed function.
        gasp_beta: Beta parameter for GASP. Small values steer towards under-segmentation,
            while high values bias towards over-segmentation. Default is 0.5. From PlantSeg gasp function.
        combine_boundary_and_semantic_edges: if True, edges are detected in the semantic image for
            the selected semantic class to yield a binary boundary label. These edges are combined with
            the input boundary label, via binary union, and this combined edge image is used as input for
            watershed and gasp algorithm. Can lead to more stable results if semantic segmentation has
            more accurate predictions of object edges.
        overwrite: If `True`, overwrite the task output.
    """
    logger.info(f"Processing {zarr_url=}")

    # Read attributes from NGFF metadata
    ngff_image_meta = load_NgffImageMeta(zarr_url)
    num_levels = ngff_image_meta.num_levels
    coarsening_xy = ngff_image_meta.coarsening_xy
    full_res_pxl_sizes_zyx = ngff_image_meta.get_pixel_sizes_zyx(level=0)
    actual_res_pxl_sizes_zyx = ngff_image_meta.get_pixel_sizes_zyx(level=level)
    logger.info(f"NGFF image has {num_levels=}")
    logger.info(f"NGFF image has {coarsening_xy=}")
    logger.info(f"NGFF image has full-res pixel sizes {full_res_pxl_sizes_zyx}")
    logger.info(f"NGFF image has level-{level} pixel sizes {actual_res_pxl_sizes_zyx}")

    # Always use masked loading for this task. TODO: with NGIO can remove this requirement
    use_masks = True

    # Load ZYX data
    # Workaround for #788: Only load channel index when there is a channel
    # dimension
    semantic_data_zyx = da.from_zarr(f"{zarr_url}/labels/{semantic_label_name}/{level}")
    boundary_data_zyx = da.from_zarr(f"{zarr_url}/labels/{boundary_label_name}/{level}")

    logger.info(f"{semantic_data_zyx.shape=}")
    logger.info(f"{boundary_data_zyx.shape=}")

    # Read ROI table
    ROI_table_path = f"{zarr_url}/tables/{masking_ROI_table}"

    if os.path.exists(ROI_table_path):
        ROI_table = ad.read_zarr(ROI_table_path)
    else:
        raise ValueError(
            f"Check task input for input_ROI_table. ROI table does not exist in {ROI_table_path=}."
        )

    # Perform some checks on the ROI table
    valid_ROI_table = is_ROI_table_valid(table_path=ROI_table_path, use_masks=use_masks)
    if use_masks and not valid_ROI_table:
        logger.info(
            f"ROI table at {ROI_table_path} cannot be used for masked "
            "loading. Set use_masks=False."
        )
        use_masks = False
    logger.info(f"{use_masks=}")

    # Create list of indices for 3D ROIs spanning the entire Z direction
    list_indices = convert_ROI_table_to_indices(
        ROI_table,
        level=level,
        coarsening_xy=coarsening_xy,
        full_res_pxl_sizes_zyx=full_res_pxl_sizes_zyx,
    )
    check_valid_ROI_indices(list_indices, masking_ROI_table)

    # If we are not planning to use masked loading, fail for overlapping ROIs
    if not use_masks:
        overlap = find_overlaps_in_ROI_indices(list_indices)
        if overlap:
            raise ValueError(
                f"ROI indices created from {masking_ROI_table} table have "
                "overlaps, but we are not using masked loading."
            )

    # Rescale datasets (only relevant for level>0)
    # Workaround for #788
    if ngff_image_meta.axes_names[0] != "c":
        new_datasets = rescale_datasets(
            datasets=[ds.model_dump() for ds in ngff_image_meta.datasets],
            coarsening_xy=coarsening_xy,
            reference_level=level,
            remove_channel_axis=False,
        )
    else:
        new_datasets = rescale_datasets(
            datasets=[ds.model_dump() for ds in ngff_image_meta.datasets],
            coarsening_xy=coarsening_xy,
            reference_level=level,
            remove_channel_axis=True,
        )

    label_attrs = {
        "image-label": {
            "version": __OME_NGFF_VERSION__,
            "source": {"image": "../../"},
        },
        "multiscales": [
            {
                "name": output_label_name,
                "version": __OME_NGFF_VERSION__,
                "axes": [
                    ax.dict()
                    for ax in ngff_image_meta.multiscale.axes
                    if ax.type != "channel"
                ],
                "datasets": new_datasets,
            }
        ],
    }

    image_group = zarr.group(zarr_url)
    label_group = prepare_label_group(
        image_group,
        output_label_name,
        overwrite=overwrite,
        label_attrs=label_attrs,
        logger=logger,
    )

    logger.info(f"Helper function `prepare_label_group` returned {label_group=}")
    logger.info(f"Output label path: {zarr_url}/labels/{output_label_name}/0")
    store = zarr.storage.FSStore(f"{zarr_url}/labels/{output_label_name}/0")
    label_dtype = np.uint32

    # Ensure that all output shapes & chunks are 3D (for 2D data: (1, y, x))
    # https://github.com/fractal-analytics-platform/fractal-tasks-core/issues/398
    shape = semantic_data_zyx.shape
    if len(shape) == 2:
        shape = (1, *shape)
    chunks = semantic_data_zyx.chunksize
    if len(chunks) == 2:
        chunks = (1, *chunks)
    mask_zarr = zarr.create(
        shape=shape,
        chunks=chunks,
        dtype=label_dtype,
        store=store,
        overwrite=False,
        dimension_separator="/",
    )

    logger.info(
        f"Instance segmentation will have shape {semantic_data_zyx.shape} "
        f"and chunks {semantic_data_zyx.chunks}"
    )

    # Initialize other things
    logger.info(f"Start semantic_to_instance_segmentation task for {zarr_url}")
    logger.info(f"level: {level}")
    logger.info("Total well shape/chunks:")
    logger.info(f"{semantic_data_zyx.shape}")
    logger.info(f"{semantic_data_zyx.chunks}")

    # Iterate over ROIs
    num_ROIs = len(list_indices)

    if output_ROI_table:
        bbox_dataframe_list = []

    logger.info(f"Now starting loop over {num_ROIs} ROIs")

    # first instance starts at 1
    starting_label_id = 1

    # ROI loaded based on masking ROI table
    for i_ROI, indices in enumerate(list_indices):
        # Define region

        # Get ROI label
        if "label" in ROI_table.obs.columns:
            roi_label = ROI_table.obs["label"].iloc[i_ROI]
        else:
            roi_label = ROI_table.obs_names[i_ROI]

        s_z, e_z, s_y, e_y, s_x, e_x = indices[:]
        region = (
            slice(s_z, e_z),
            slice(s_y, e_y),
            slice(s_x, e_x),
        )
        logger.info(f"Now processing ROI {i_ROI + 1}/{num_ROIs}, label: {roi_label}")

        semantic_img_np = np.expand_dims(
            load_region(semantic_data_zyx, region, compute=True, return_as_3D=True),
            axis=0,
        )
        boundary_img_np = np.expand_dims(
            load_region(boundary_data_zyx, region, compute=True, return_as_3D=True),
            axis=0,
        )

        # Prepare keyword arguments for preprocessing function
        preprocessing_kwargs = {}
        if use_masks:
            preprocessing_kwargs = {
                "region": region,
                "current_label_path": f"{zarr_url}/labels/{output_label_name}/0",
                "ROI_table_path": ROI_table_path,
                "ROI_positional_index": i_ROI,
                "level": level,
            }

        # Mask semantic segmentation as well
        (
            semantic_img_np_masked,
            _,
            _,
        ) = _preprocess_input(semantic_img_np, **preprocessing_kwargs)

        # Prepare keyword arguments for segment_ROI function
        kwargs_segment_roi = {
            "semantic_seg": semantic_img_np_masked,
            "select_semantic_class": select_semantic_class,
            "pixmeta": actual_res_pxl_sizes_zyx,
            "starting_label_id": starting_label_id,
            "gaussian_sigma": gaussian_sigma,
            "watershed_threshold": watershed_threshold,
            "watershed_sigma_seeds": watershed_sigma_seeds,
            "watershed_sigma_weights": watershed_sigma_weights,
            "watershed_alpha": watershed_alpha,
            "watershed_min_size": watershed_min_size,
            "gasp_beta": gasp_beta,
            "combine_boundary_and_semantic_edges": combine_boundary_and_semantic_edges,
        }
        # Call segment_ROI through the masked-loading wrapper, which includes
        # pre/post-processing functions if needed
        new_label_img, instance_count = masked_loading_wrapper(
            image_array=boundary_img_np,
            function=run_semantic_to_instance_segmentation,
            kwargs=kwargs_segment_roi,
            use_masks=use_masks,
            preprocessing_kwargs=preprocessing_kwargs,
        )

        # return None if boundary region is empty and continue to next ROI
        if new_label_img is None and instance_count is None:
            logger.info(f"Empty boundary image in region {i_ROI}, skipping.")
            continue

        logger.info(
            f"Identified {instance_count} instances for class {select_semantic_class} in region {i_ROI + 1}."
        )
        # update starting label so that next region is increasing sequentially
        starting_label_id = starting_label_id + instance_count

        if output_ROI_table:
            bbox_df = array_to_bounding_box_table(
                new_label_img,
                actual_res_pxl_sizes_zyx,
                origin_zyx=(s_z, s_y, s_x),
            )

            bbox_dataframe_list.append(bbox_df)

        # Compute and store 0-th level to disk
        da.array(new_label_img).to_zarr(
            url=mask_zarr,
            region=region,
            compute=True,
        )

    logger.info(
        f"End semantic_to_instance_segmentation task for {zarr_url}, "
        "now building pyramids."
    )

    # Starting from on-disk highest-resolution data, build and write to disk a
    # pyramid of coarser levels
    build_pyramid(
        zarrurl=f"{zarr_url}/labels/{output_label_name}",
        overwrite=overwrite,
        num_levels=num_levels,
        coarsening_xy=coarsening_xy,
        chunksize=chunks,
        aggregation_function=np.max,
    )

    logger.info("End building pyramids")

    if output_ROI_table:
        bbox_table = create_roi_table_from_df_list(bbox_dataframe_list)

        # Write to zarr group
        image_group = zarr.group(zarr_url)
        logger.info(
            "Now writing bounding-box ROI table to "
            f"{zarr_url}/tables/{output_ROI_table}"
        )
        table_attrs = {
            "type": "masking_roi_table",
            "region": {"path": f"../labels/{output_label_name}"},
            "instance_key": "label",
        }
        write_table(
            image_group,
            output_ROI_table,
            bbox_table,
            overwrite=overwrite,
            table_attrs=table_attrs,
        )


if __name__ == "__main__":
    from fractal_tasks_core.tasks._utils import run_fractal_task

    run_fractal_task(
        task_function=semantic_to_instance_segmentation,
        logger_name=logger.name,
    )
